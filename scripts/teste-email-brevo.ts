import { montarCorpoBrevo, renderEmailHtml, renderEmailTexto } from '../lib/email-brevo';
import { emailFailureText } from '../lib/email-failure';
let ok = 0, tot = 0; const t = (n: string, c: boolean) => { tot++; if (c) ok++; else console.log('FALHOU:', n); };
const base = { toEmail: ' aluno@x.com ', toName: 'Ana <b>Maria</b>', title: 'Aula "agendada" & confirmada', message: 'Linha 1\nLink da aula: https://meet.google.com/abc-defg-hij.\nFim', buttonLabel: 'Ver minhas aulas', buttonUrl: 'https://www.agendapromusic.com.br/aluno/dashboard' };
const html = renderEmailHtml(base);
t('escapa HTML do nome', html.includes('Ana &lt;b&gt;Maria&lt;/b&gt;') && !html.includes('<b>Maria'));
t('escapa título', html.includes('Aula &quot;agendada&quot; &amp; confirmada'));
t('quebra de linha vira <br>', html.includes('Linha 1<br>Link da aula:'));
t('link do Meet clicável sem o ponto final', html.includes('<a href="https://meet.google.com/abc-defg-hij" target="_blank"') && html.includes('</a>.<br>Fim'));
t('botão com o link', html.includes('href="https://www.agendapromusic.com.br/aluno/dashboard"') && html.includes('Ver minhas aulas'));
t('logo presente', html.includes('email-logo.png'));
t('link perigoso vira #', renderEmailHtml({ ...base, buttonUrl: 'javascript:alert(1)' }).includes('href="#"'));
const texto = renderEmailTexto(base);
t('texto simples traz o link do botão', texto.includes('Ver minhas aulas: https://www.agendapromusic.com.br/aluno/dashboard'));
const c = montarCorpoBrevo(base);
t('corpo: remetente do domínio', c.sender.email === 'notificacoes@agendapromusic.com.br' && c.sender.name === 'Agenda Pro Music');
t('corpo: destinatário limpo', c.to[0].email === 'aluno@x.com');
t('corpo: assunto = título', c.subject === base.title);
t('corpo: sem nome não manda name', montarCorpoBrevo({ ...base, toName: '' }).to[0].name === undefined);
t('erro 401 explica a chave', emailFailureText({ reason: 'api', detail: 'Brevo HTTP 401: {"message":"Key not found"}' }).includes('BREVO_API_KEY'));
t('erro de remetente explica', emailFailureText({ reason: 'api', detail: 'Brevo HTTP 400: sender not valid' }).includes('Remetentes'));
t('erro EmailJS continua igual', emailFailureText({ reason: 'api', detail: 'HTTP 429: quota exceeded' }).includes('EmailJS'));
console.log(`${ok} de ${tot}`);
